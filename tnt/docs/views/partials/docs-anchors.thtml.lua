{{-- Оглавление страницы: заголовки h2 и h3 с якорями.

     Кусок подключается дважды: колонкой справа на широком экране
     (`docs.layout`) и телом липкого `<details>` на узком
     (`partials.docs-table-of-contents`). Один и тот же список в двух
     местах — потому и кусок: второй, написанный отдельно, разошёлся бы
     с первым на первой же правке.

     Уровень заголовка уходит в класс пункта (`anchor-h2`, `anchor-h3`),
     а не в стиль отступа: ступенька — оформление, и её место в таблице
     стилей, а не в разметке.

     Текущий раздел отмечает контроллер `docs` — атрибутом
     `aria-current="location"`, а не классом: «здесь читатель сейчас» —
     это уже описанное состояние, и чтец объявляет его сам.

     Клик — плавная прокрутка контроллером `scroll`: обычный переход
     по якорю прыгает к заголовку рывком, а адрес страницы обрастает
     хвостом в истории браузера.

     Данные: `outline` — заголовки страницы (`page.outline`). --}}
<nav class="anchors" aria-label="Оглавление страницы">
    <ul>
        @for (_, heading in ipairs(outline))
        <li class="anchor-h{{ heading.level }}">
            <a href="#{{ heading.anchor }}"
               data-controller="scroll"
               data-action="click->scroll#go"
               data-scroll-to-value="#{{ heading.anchor }}">{{ heading.text }}</a>
        </li>
        @endfor
    </ul>
</nav>
