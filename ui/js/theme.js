// Тема страницы — до первой отрисовки.
//
// Сценарий стоит в <head> без `defer` и `async`: страница, нарисованная
// светлой и перекрашенная после загрузки, мигала бы на каждом открытии.
// Строкой внутри страницы его не написать — правило источников узла
// (Content-Security-Policy) встроенных сценариев не пускает, — поэтому
// он приходит отдельным крошечным файлом. Дальше тему ведёт контроллер
// `theme`; ключ памяти у них один.
//
// Выбор посетителя — `light`, `dark` или `auto`; `auto` и пустая память —
// тема системы. Память браузера бывает закрыта вовсе (запрет cookie),
// и тогда чтение бросает: тема системы лучше страницы без темы.

let theme = 'auto';

try {
    theme = localStorage.getItem('theme') ?? 'auto';
} catch {
    // Памяти нет — тема системы.
}

if (theme !== 'light' && theme !== 'dark') {
    theme = window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
}

document.documentElement.setAttribute('data-bs-theme', theme);
